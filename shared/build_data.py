"""Extract per-unit 'typical profile' data from the BRO Bodemkaart GeoPackages into profiles_data.js.
Unit -> profile: the profile ID assigned to polygons of that unit (most frequent one if several).
Depths: soilhorizon uppervalue = bottom, lowervalue = top (metres, names swapped in the source); soillayer depths are cm."""
import sqlite3, json, collections
D = r"C:/Users/brand153/Desktop/PhD_working_directory/Data/Raw_unzipped/Bodemdata/Levering-BRO-SGM-V2025-01_1/"
c = sqlite3.connect("file:" + D + "BRO-SGM-DownloadBodemkaart-V2025-01_1.gpkg?mode=ro", uri=True)
c.execute("attach database 'file:" + D + "BRO-SGM-Bodemkaart-V2025-01_1.gpkg?mode=ro' as flat")
q = lambda s, *a: c.execute(s, a).fetchall()
r2 = lambda x, n=2: None if x is None else round(x, n)

profiles = {}
for pid, unit, name, region in q("select normalsoilprofile_id, soilunit, othersoilname, region from normalsoilprofiles"):
    hz = [dict(n=n, top=round(lo * 100), bot=round(up * 100), om=om, om_min=omn, om_max=omx, lut_min=ln, lut_max=lx,
               loam_min=lon, loam_max=lox, sand=sm, ca=ca, fe=fe, peat=pt, ph=ac)
          for n, lo, up, om, omn, omx, ln, lx, lon, lox, sm, ca, fe, pt, ac in q(
              """select faohorizonnotation, lowervalue, uppervalue, organicmattercontent, minimumorganicmattercontent,
                        maximumorganicmattercontent, minimumlutitecontent, maximumlutitecontent, minimumloamcontent,
                        maximumloamcontent, sandmedian, calciccontent, fedith, peattype, acidity
                 from soilhorizon where normalsoilprofile_id=? order by layernumber""", pid)]
    ly = [dict(top=lo, bot=up, dep=d) for lo, up, d in q(
        "select lowervalue, uppervalue, depositionalcharacteristic from soillayer where normalsoilprofile_id=? order by layersequencenumber", pid)]
    lu = [r[0] for r in q("select landuse from normalsoilprofiles_landuse where normalsoilprofile_id=?", pid)]
    profiles[pid] = dict(id=pid, unit=unit, name=name, region=region, hz=hz, layers=ly, landuse=lu)

units = {}
rows = q("""select a.first_soilcode, a.first_soilname, u.mainsoilclassification, n.normalsoilprofile_id, count(*)
            from flat.soilarea a join soilarea_normalsoilprofile n on n.maparea_id = a.maparea_id
            left join soil_units u on u.code = a.first_soilcode
            group by 1,2,3,4""")
by = collections.defaultdict(list)
for code, nm, main, pid, k in rows: by[code].append((k, pid, nm, main))
for code, lst in by.items():
    lst.sort(reverse=True)
    units[code] = dict(code=code, name=lst[0][2], main=lst[0][3], profile=lst[0][1],
                       polygons=sum(k for k, *_ in lst), versions=[[p, k] for k, p, *_ in lst])
# Map codes: the main unit of every polygon (text before '/'), split into prefix letters (top-layer additions),
# base legend unit and suffix letters (bottom-layer additions). v = [[profile id, polygons], ...] most frequent first.
acc = collections.defaultdict(lambda: dict(u=None, p="", s="", v=collections.Counter()))
for sc, base, pid, k in q("""select a.soilcode, a.first_soilcode, n.normalsoilprofile_id, count(*)
                              from flat.soilarea a join soilarea_normalsoilprofile n on n.maparea_id = a.maparea_id group by 1,2,3"""):
    main = sc.split("/")[0]
    i = main.find(base)
    assert i >= 0, (sc, base)
    e = acc[main]
    assert e["u"] in (None, base), (main, e["u"], base)
    e["u"], e["p"], e["s"] = base, main[:i], main[i + len(base):]
    e["v"][pid] += k
codes = {m: dict(u=e["u"], p=e["p"], s=e["s"], n=sum(e["v"].values()), v=[[pid, k] for pid, k in e["v"].most_common()]) for m, e in acc.items()}

with open("profiles_data.js", "w", encoding="utf-8") as f:
    f.write("// generated by build_data.py from BRO Bodemkaart V2025-01 (CC0)\nwindow.PROFILES=" + json.dumps(profiles, separators=(",", ":")) +
            ";\nwindow.UNITS=" + json.dumps(units, separators=(",", ":")) +
            ";\nwindow.MAIN_CLASSES=" + json.dumps(sorted({u["main"] for u in units.values() if u["main"]}), ensure_ascii=False, separators=(",", ":")) +
            ";\nwindow.CODES=" + json.dumps(codes, separators=(",", ":")) + ";\n")
print(len(codes), "map codes;", len(profiles), "profiles;", len(units), "units;", "units with >1 profile:", sum(len(u["versions"]) > 1 for u in units.values()))
for k in ["pZg23", "hVc", "Rd90C", "Hn21", "Mn15A"]:
    u = units.get(k); print(k, u and (u["name"], u["profile"], u["polygons"], u["versions"]))

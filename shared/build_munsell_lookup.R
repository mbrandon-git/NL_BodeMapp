# Exports a small Munsell -> hex lookup (hue x value x chroma) for the prototype page.
# Source: Munsell renotation data as shipped in the R 'munsell' package (v0.5.1); chips with integer value and even chroma only.
suppressMessages(library(munsell))
m <- munsell:::munsell.map
hues <- c("5YR","7.5YR","10YR","2.5Y","5Y","7.5Y","10Y","5GY","N")
m <- m[as.character(m$hue) %in% hues & m$value >= 1 & m$value <= 9 & m$chroma <= 8, ]
out <- vapply(hues, function(h) {
  s <- m[as.character(m$hue) == h, ]
  vals <- split(s, s$value)
  paste0('"', h, '":{', paste(vapply(names(vals), function(v) {
    x <- vals[[v]]; paste0('"', v, '":{', paste0('"', x$chroma, '":"', x$hex, '"', collapse = ","), '}')
  }, ""), collapse = ","), '}')
}, "")
writeLines(paste0("// generated by build_munsell_lookup.R\nwindow.MUNSELL={", paste(out, collapse = ","), "};"), "munsell_lookup.js")
cat("chips:", nrow(m), "\n")

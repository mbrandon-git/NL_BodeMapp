"""Builds shared/translations.js (used by the app) from shared/translations.csv (edited by people).
Edit the CSV (Excel or any text editor, UTF-8), then run `python build.py` in the project folder, or this script directly.
Rows with an empty `english` column are skipped, so those terms stay in Dutch in the app.
A row counts as reviewed when its `status` starts with "reviewed"; everything else is a draft."""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
dicts = {}
shorts = {}
confs = {}
total = reviewed = 0
with open(os.path.join(HERE, "translations.csv"), encoding="utf-8-sig", newline="") as f:
    for row in csv.DictReader(f):
        if not row["english"].strip():
            continue
        dicts.setdefault(row["category"], {})[row["dutch"]] = row["english"].strip()
        if row.get("english_short", "").strip():
            shorts.setdefault(row["category"], {})[row["dutch"]] = row["english_short"].strip()
        confs.setdefault(row["category"], {})[row["dutch"]] = row.get("confidence", "").strip()
        total += 1
        if row["status"].strip().lower().startswith("reviewed"):
            reviewed += 1
js = ("// generated by build_translations.py from translations.csv: edit the CSV, not this file\n"
      "window.TRANSLATIONS=" + json.dumps(dicts, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "window.TRANSLATIONS_SHORT=" + json.dumps(shorts, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "window.TRANSLATIONS_CONF=" + json.dumps(confs, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "window.TRANSLATIONS_META=" + json.dumps({"total": total, "reviewed": reviewed}) + ";\n")
with open(os.path.join(HERE, "translations.js"), "w", encoding="utf-8") as f:
    f.write(js)
print("translations.js:", total, "translations,", reviewed, "reviewed by an expert")
